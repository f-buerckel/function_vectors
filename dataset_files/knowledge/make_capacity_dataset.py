"""
Generates fictional_people_capacity.json: 8 fictional people with 8 city facts each, for testing how many facts
one vector can hold. Setup-only, not the research dataset.

Usage (from this folder): python make_capacity_dataset.py
"""
import json, random

SEED = 0
CITIES = ["Lisbon", "Oslo", "Seoul", "Nairobi", "Madrid", "Cairo", "Vienna", "Lima",
          "Dublin", "Prague", "Athens", "Boston", "Sydney", "Toronto", "Mumbai", "Chicago"]  # all single tokens for Qwen3
NAMES = ["Arlen Tovik", "Brisa Halloway", "Corwin Destrel", "Delphine Marrow",
         "Emrys Calloway", "Fenna Ostrova", "Gideon Larch", "Halcyon Brett"]
TEMPLATES = {
    "born_city": {"demo": "Where was {name} born?", "extract": ["In which city was {name} born?", "What is the birthplace of {name}?"],
                  "test": "Which city is the birthplace of {name}?"},
    "work_city": {"demo": "Where does {name} work?", "extract": ["In which city does {name} work?", "What city is the workplace of {name}?"],
                  "test": "Which city does {name} work in?"},
    "study_city": {"demo": "Where did {name} study?", "extract": ["In which city did {name} study?", "What city did {name} attend university in?"],
                   "test": "Which city did {name} go to university in?"},
    "home_city": {"demo": "Where does {name} live?", "extract": ["In which city does {name} live?", "What city is the home of {name}?"],
                  "test": "Which city does {name} live in?"},
    "married_city": {"demo": "Where did {name} get married?", "extract": ["In which city did {name} get married?", "What city was the wedding of {name} in?"],
                     "test": "Which city did {name} marry in?"},
    "childhood_city": {"demo": "Where did {name} grow up?", "extract": ["In which city did {name} grow up?", "What city did {name} spend their childhood in?"],
                       "test": "Which city was {name} raised in?"},
    "vacation_city": {"demo": "Where does {name} go on vacation?", "extract": ["In which city does {name} spend their holidays?", "What city does {name} travel to on vacation?"],
                      "test": "Which city does {name} visit on holiday?"},
    "retire_city": {"demo": "Where does {name} plan to retire?", "extract": ["In which city does {name} want to retire?", "What city has {name} chosen for retirement?"],
                    "test": "Which city will {name} retire to?"},
}

rng = random.Random(SEED)
people = [{"name": name, "facts": dict(zip(TEMPLATES, rng.sample(CITIES, len(TEMPLATES))))} for name in NAMES]
data = {"_note": "Setup-only dataset for testing how many facts one vector can hold. Generated by make_capacity_dataset.py.",
        "templates": TEMPLATES, "people": people}
with open("fictional_people_capacity.json", "w") as f:
    json.dump(data, f, indent=2)
print(f"Wrote {len(people)} people with {len(TEMPLATES)} facts each")
